def main():
    data = dict(generated=VERIFIED, categories=CATEGORIES, resources=RESOURCES, emergency=EMERGENCY, fuel=FUEL,
                calendar=CALENDAR, scholarships=SCHOLARSHIPS, notices=NOTICES)
    out = ROOT / "resources"; out.mkdir(exist_ok=True)
    (out / "data.json").write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")

    def lit(v):
        if v is None: return "null"
        if isinstance(v, bool): return "true" if v else "false"
        if isinstance(v, (int, float)): return str(v)
        if isinstance(v, (list, dict)): return "'" + json.dumps(v, ensure_ascii=False).replace("'", "''") + "'::jsonb"
        return "'" + str(v).replace("'", "''") + "'"
    def arr(v): return "array[" + ",".join(lit(x) for x in v) + "]::text[]" if v else "'{}'::text[]"
    def ins(table, rows, conflict, cols, special=None):
        lines = []
        for r in rows:
            vals = []
            for c in cols:
                if special and c in special: vals.append(special[c](r[c]))
                else: vals.append(lit(r.get(c)))
            lines.append("(" + ", ".join(vals) + ")")
        return f"insert into public.{table} ({', '.join(cols)}) values\n  " + ",\n  ".join(lines) + f"\non conflict {conflict} do nothing;\n"

    sql = ["-- Generated by tools/resources_seed.py — content verified " + VERIFIED + ". Safe to run again.\n"]
    sql.append(ins("resource_categories", CATEGORIES, "(slug)", ["slug", "name", "description", "icon", "sort_order", "is_active", "ad_category"]))
    sql.append(ins("public_resources", RESOURCES, "(slug)",
        ["slug", "category_slug", "title", "summary", "content", "county", "apply_url", "apply_label", "source_name", "source_url",
         "verification_status", "published_at", "last_verified", "next_review", "tags", "status", "sort_order"], {"tags": arr}))
    sql.append(ins("emergency_contacts", [dict(e, last_verified=VERIFIED, status="published") for e in EMERGENCY], "(number)",
        ["name", "number", "description", "available", "sort_order", "source_name", "source_url", "last_verified", "status"]))
    sql.append(ins("fuel_prices", FUEL, "(cycle_start, town)", ["cycle_start", "cycle_end", "town", "petrol", "diesel", "kerosene", "source_url", "verified", "status"]))
    sql.append(ins("education_calendar", CALENDAR, "(title, start_date)",
        ["title", "event_type", "level", "start_date", "end_date", "source_name", "source_url", "last_verified", "status", "notes"]))
    sql.append(ins("scholarships", SCHOLARSHIPS, "(name)",
        ["name", "institution", "country", "level", "eligibility", "coverage", "deadline", "opens_on", "url", "open_status", "notes", "last_verified", "next_review", "status"]))
    sql.append(ins("public_notices", NOTICES, "(title)",
        ["category_slug", "title", "summary", "county", "source_name", "source_url", "starts_at", "ends_at", "origin", "status"]))
    sql.append(ins("resource_sources", [dict(name=a, url=b, kind=c, automation=d, terms_note=e, last_checked=VERIFIED) for a, b, c, d, e in SOURCES], "(url)",
        ["name", "url", "kind", "automation", "terms_note", "last_checked"]))
    (ROOT / "supabase" / "resources-seed.sql").write_text("\n".join(sql), encoding="utf-8")
    counts = {c["slug"]: sum(1 for r in RESOURCES if r["category_slug"] == c["slug"]) for c in CATEGORIES if c["is_active"]}
    print("resources per category:", counts, "| scholarships", len(SCHOLARSHIPS), "| fuel rows", len(FUEL), "| calendar", len(CALENDAR))

if __name__ == "__main__":
    main()
