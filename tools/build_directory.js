// Builds the search-friendly pages of the IMMA Business Directory from Supabase.
//
//   node tools/build_directory.js
//
// Reads only the public, privacy-safe views (dir_*) with the public anon key, and writes:
//   business-directory/<slug>/index.html                 one page per approved business
//   business-directory/<category>/index.html             category pages   (only when they have listings)
//   business-directory/<category>/<county>/index.html    category + county (only when they have listings)
//   business-directory/county/<county>/index.html        county pages
//   business-directory/county/<county>/<town>/index.html town pages
//   sitemap.xml                                          /business-directory/ entries replaced
// Pages of businesses that are no longer approved are removed. Then runs build_footer.js.
// Run after approving listings, then commit and push.
"use strict";
const fs = require("fs"), path = require("path"), vm = require("vm"), cp = require("child_process");
const ROOT = path.resolve(__dirname, "..");
const DIR = path.join(ROOT, "business-directory");
const SITE = "https://immanews.com";
const MARK = "<!-- generated by tools/build_directory.js -->";
const FIXED = new Set(["index.html", "listing.html", "register.html", "dashboard.html", "terms.html", "invoice.html"]);

const sb = {}; vm.createContext(sb);
vm.runInContext(fs.readFileSync(path.join(ROOT, "config.js"), "utf8") + ";this.SUPABASE = typeof SUPABASE !== 'undefined' ? SUPABASE : this.SUPABASE;", sb);
global.SUPABASE = sb.SUPABASE;
const D = require(path.join(ROOT, "directory-common.js"));
const { esc } = D;
const json = (o) => JSON.stringify(o).replace(/</g, "\\u003c");

async function get(table, query) {
  const r = await fetch(`${SUPABASE.url}/rest/v1/${table}?${query}`, { headers: { apikey: SUPABASE.anonKey, Authorization: "Bearer " + SUPABASE.anonKey } });
  if (!r.ok) throw new Error(`${table}: HTTP ${r.status} ${await r.text()}`);
  return r.json();
}

