const written = new Set();
function write(rel, html) {
  const file = path.join(DIR, rel, "index.html");
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (fs.existsSync(file)) {   // keep the footer baked last time
    const old = fs.readFileSync(file, "utf8"), a = old.indexOf("<!-- SITE-FOOTER:START"), b = old.indexOf("<!-- SITE-FOOTER:END -->");
    if (a >= 0 && b > a) html = html.replace(/<!-- SITE-FOOTER:START[^>]*-->\s*<!-- SITE-FOOTER:END -->/, old.slice(a, b + "<!-- SITE-FOOTER:END -->".length));
  }
  fs.writeFileSync(file, html);
  written.add(path.normalize(file));
}

function listPage({ rel, h1, intro, list, crumbs, title, description, links }) {
  const url = `${SITE}/business-directory/${rel}/`;
  const ld = { "@context": "https://schema.org", "@graph": [
    { "@type": "CollectionPage", "@id": url, url, name: h1, description, isPartOf: { "@id": SITE + "/#website" },
      mainEntity: { "@type": "ItemList", itemListElement: list.slice(0, 50).map((b, i) => ({ "@type": "ListItem", position: i + 1, url: SITE + D.profileUrl(b), name: b.name })) } },
    crumbsLd(crumbs)] };
  const sorted = list.slice().sort((a, b) => (b.featured - a.featured) || (b.verified - a.verified) || (b.rating_avg - a.rating_avg) || a.name.localeCompare(b.name));
  return head({ title, description, url, ld }) + `
  <main id="main">
    ${crumbsHtml(crumbs)}
    <section class="wrap" style="padding:18px 0 8px"><p class="bd-eyebrow" style="color:var(--brand)">IMMA Business Directory</p><h1 style="margin:0 0 8px">${esc(h1)}</h1><p class="bd-muted" style="max-width:760px;line-height:1.6">${esc(intro)}</p></section>
    <section class="wrap bd-block-sec" style="padding-top:10px"><div class="bd-grid">${sorted.map((b) => D.card(b, { showOpen: false })).join("")}</div></section>
    ${links ? `<section class="wrap bd-block-sec"><h2 style="font-size:1.2rem">${esc(links.title)}</h2><p class="bd-chips">${links.items.map(([n, u]) => `<a href="${u}" style="padding:6px 12px;border-radius:99px;border:1px solid var(--line);text-decoration:none;color:var(--text)">${esc(n)}</a>`).join("")}</p></section>` : ""}
    <section class="wrap bd-block-sec"><div class="bd-empty"><h3>Own a business here?</h3><p>Listing on the IMMA Business Directory is free.</p><p><a class="bd-btn" href="/business-directory/register.html">List your business</a></p></div></section>
  </main>
` + FOOT("");
}

(async () => {
  if (!SUPABASE || !SUPABASE.url) throw new Error("config.js has no Supabase settings.");
  const [biz, images, products, services, promos, reviews, cats] = await Promise.all([
    get("dir_businesses", "select=*&order=name"),
    get("dir_images", "select=*&order=sort_order"),
    get("dir_products", "select=*&order=sort_order"),
    get("dir_services", "select=*&order=sort_order"),
    get("dir_promotions", "select=*"),
    get("dir_reviews", "select=*&order=created_at.desc"),
    get("business_categories", "select=id,slug,name,parent_id&active=eq.true")
  ]);
  const by = (arr, id) => arr.filter((x) => x.business_id === id);
  const sm = [];

  // Business profiles
  for (const b of biz) {
    const x = { images: by(images, b.id), products: by(products, b.id), services: by(services, b.id), promotions: by(promos, b.id), reviews: by(reviews, b.id).slice(0, 30) };
    const place = [b.town, b.county ? D.countyName(b.county) : ""].filter(Boolean).join(", ");
    const base = `${b.name}${b.town ? " in " + b.town : ""}`;
    const title = (base + " · IMMA Business Directory").length <= 60 ? base + " · IMMA Business Directory" : (base + " · " + (b.category_name || "Business")).length <= 60 ? base + " · " + (b.category_name || "Business") : base.slice(0, 60);
    const description = (b.tagline ? b.tagline + ". " : "") + String(b.description || "").replace(/\s+/g, " ");
    const desc = description.length > 155 ? description.slice(0, 152).replace(/\s+\S*$/, "") + "…" : description;
    const thin = String(b.description || "").length < 80 && !x.products.length && !x.services.length;   // keep thin listings out of Google
    const crumbs = [["Home", "/"], ["Business Directory", "/business-directory/"], [b.category_name || "Businesses", `/business-directory/${b.category_slug}/`], ...(b.county ? [[D.countyName(b.county), `/business-directory/${b.category_slug}/${b.county}/`]] : []), [b.name, D.profileUrl(b)]];
    const ld = { "@context": "https://schema.org", "@graph": [Object.assign(D.jsonLd(b, x), { "@context": undefined }), crumbsLd(crumbs)] };
    write(b.slug, head({ title, description: desc || `${b.name}, ${place}.`, url: SITE + D.profileUrl(b), image: b.cover_path ? D.media(b.cover_path) : b.logo_path ? D.media(b.logo_path) : null, ld, robots: thin ? "noindex, follow" : "index, follow, max-image-preview:large" }) + `
  <main id="main">
    ${crumbsHtml(crumbs)}
    ${D.profile(b, x)}
  </main>
` + FOOT('  <script src="/directory-profile.js"></script>\n'));
    if (!thin) sm.push([D.profileUrl(b), (b.updated_at || b.published_at || "").slice(0, 10)]);
  }

  // Landing pages: only where listings exist
  const top = cats.filter((c) => !c.parent_id);
  const byCat = {}; biz.forEach((b) => { if (b.category_slug) (byCat[b.category_slug] = byCat[b.category_slug] || []).push(b); });
  for (const [slug, list] of Object.entries(byCat)) {
    const cat = top.find((c) => c.slug === slug); if (!cat) continue;
    const counties = [...new Set(list.map((b) => b.county).filter(Boolean))].sort();
    write(slug, listPage({ rel: slug, h1: `${cat.name} in Kenya`, list, crumbs: [["Home", "/"], ["Business Directory", "/business-directory/"], [cat.name, `/business-directory/${slug}/`]],
      title: `${cat.name} in Kenya · IMMA Business Directory`, description: `Find ${cat.name.toLowerCase()} across Kenya on the IMMA Business Directory: contacts, locations, opening hours and reviews.`,
      intro: `${list.length} listed ${list.length === 1 ? "business" : "businesses"} in ${cat.name.toLowerCase()} across Kenya. Contact them directly by phone or WhatsApp.`,
      links: counties.length ? { title: "By county", items: counties.map((c) => [D.countyName(c), `/business-directory/${slug}/${c}/`]) } : null }));
    sm.push([`/business-directory/${slug}/`, ""]);
    for (const c of counties) {
      const l2 = list.filter((b) => b.county === c);
      write(`${slug}/${c}`, listPage({ rel: `${slug}/${c}`, h1: `${cat.name} in ${D.countyName(c)}`, list: l2,
        crumbs: [["Home", "/"], ["Business Directory", "/business-directory/"], [cat.name, `/business-directory/${slug}/`], [D.countyName(c), `/business-directory/${slug}/${c}/`]],
        title: `${cat.name} in ${D.countyName(c)} · IMMA Business Directory`, description: `${cat.name} in ${D.countyName(c)} County, Kenya: contacts, locations, opening hours and customer reviews on the IMMA Business Directory.`,
        intro: `${l2.length} ${cat.name.toLowerCase()} listed in ${D.countyName(c)} County.` }));
      sm.push([`/business-directory/${slug}/${c}/`, ""]);
    }
  }
  const byCounty = {}; biz.forEach((b) => { if (b.county) (byCounty[b.county] = byCounty[b.county] || []).push(b); });
  for (const [c, list] of Object.entries(byCounty)) {
    const towns = {}; list.forEach((b) => { if (b.town) { const t = D.slugify(b.town); (towns[t] = towns[t] || { name: b.town, list: [] }).list.push(b); } });
    write(`county/${c}`, listPage({ rel: `county/${c}`, h1: `Businesses in ${D.countyName(c)}`, list, crumbs: [["Home", "/"], ["Business Directory", "/business-directory/"], [D.countyName(c), `/business-directory/county/${c}/`]],
      title: `Businesses in ${D.countyName(c)} County · IMMA Business Directory`, description: `Local businesses in ${D.countyName(c)} County, Kenya: shops, services, food, health and more on the IMMA Business Directory.`,
      intro: `${list.length} listed ${list.length === 1 ? "business" : "businesses"} in ${D.countyName(c)} County.`,
      links: { title: "By town", items: Object.entries(towns).map(([t, o]) => [o.name, `/business-directory/county/${c}/${t}/`]) } }));
    sm.push([`/business-directory/county/${c}/`, ""]);
    for (const [t, o] of Object.entries(towns)) {
      if (!t) continue;
      write(`county/${c}/${t}`, listPage({ rel: `county/${c}/${t}`, h1: `Businesses in ${o.name}`, list: o.list,
        crumbs: [["Home", "/"], ["Business Directory", "/business-directory/"], [D.countyName(c), `/business-directory/county/${c}/`], [o.name, `/business-directory/county/${c}/${t}/`]],
        title: `Businesses in ${o.name}, ${D.countyName(c)} · IMMA Business Directory`, description: `Local businesses in ${o.name}, ${D.countyName(c)} County: contacts, opening hours and reviews on the IMMA Business Directory.`,
        intro: `${o.list.length} listed ${o.list.length === 1 ? "business" : "businesses"} in ${o.name}.` }));
      sm.push([`/business-directory/county/${c}/${t}/`, ""]);
    }
  }

  // Remove generated pages that are no longer needed (never the fixed pages)
  (function prune(dir) {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const f = path.join(dir, e.name);
      if (e.isDirectory()) { prune(f); if (!fs.readdirSync(f).length) fs.rmdirSync(f); }
      else if (e.name === "index.html" && dir !== DIR && !written.has(path.normalize(f)) && fs.readFileSync(f, "utf8").includes(MARK)) { fs.unlinkSync(f); console.log("removed", path.relative(ROOT, f)); }
    }
  })(DIR);
  void FIXED;

  // sitemap.xml
  const SM = path.join(ROOT, "sitemap.xml");
  let s = fs.readFileSync(SM, "utf8").replace(/\s*<url><loc>https:\/\/immanews\.com\/business-directory\/[^<]*<\/loc>(<lastmod>[^<]*<\/lastmod>)?<\/url>/g, "");
  const entries = [["/business-directory/", ""], ["/business-directory/terms.html", ""], ...sm];
  s = s.replace(/\s*<\/urlset>\s*$/, "\n" + entries.map(([u, d]) => `  <url><loc>${SITE}${u}</loc>${d ? `<lastmod>${d}</lastmod>` : ""}</url>`).join("\n") + "\n</urlset>\n");
  fs.writeFileSync(SM, s);
  console.log(`directory: ${biz.length} business page(s); ${sm.length} address(es) in the sitemap`);

  if (!process.env.IMMA_NO_FOOTER) cp.execFileSync(process.execPath, [path.join(__dirname, "build_footer.js")], { stdio: "inherit" });
})().catch((e) => { console.error(e.message || e); process.exit(1); });
