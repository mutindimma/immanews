// Bakes the global footer (footer.js DEFAULTS) into every public page as static HTML,
// and makes sure each page loads footer.css and footer.js. Also rebuilds feed.xml.
//
//   node tools/build_footer.js
//
// Run it after changing footer.js defaults, adding a page, or adding stories to news.js.
// Changes administrators make in the dashboard do not need a rebuild (they load live).
"use strict";
const fs = require("fs"), path = require("path"), vm = require("vm");
const ROOT = path.resolve(__dirname, "..");
const F = require(path.join(ROOT, "footer.js"));

const SKIP = new Set(["ads-admin.html", "resources-admin.html", "directory-admin.html", "invoice.html", "google"]);   // admin / print pages
const START = "<!-- SITE-FOOTER:START (generated by tools/build_footer.js from footer.js; do not edit here) -->";
const END = "<!-- SITE-FOOTER:END -->";
const NO_CTA = new Set(["advertise.html", "advertiser.html"]);
const H = require(path.join(ROOT, "header.js"));
const HSTART = "<!-- SITE-HEADER:START (generated by tools/build_footer.js from header.js; do not edit here) -->", HEND = "<!-- SITE-HEADER:END -->";
const FONT_URL = "https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&amp;family=Playfair+Display:ital,wght@0,600;0,700;0,800;1,600&amp;family=Source+Serif+4:ital,opsz,wght@0,8..60,400;0,8..60,600;1,8..60,400&amp;display=swap";

// Story categories (for links shown only when a category has stories)
const sandbox = { window: {}, console };
vm.createContext(sandbox);
for (const f of ["news.js", "series-feed.js"]) {
  const p = path.join(ROOT, f);
  if (fs.existsSync(p)) vm.runInContext(fs.readFileSync(p, "utf8") + "\n;this.NEWS = typeof NEWS !== 'undefined' ? NEWS : this.NEWS;", sandbox);
}
const NEWS = sandbox.NEWS || [];
const SERIES = sandbox.window.SERIES_FEED || [];
const cats = new Set([...NEWS, ...SERIES].map((n) => n.category).filter(Boolean));
const year = new Date().getFullYear();
const SECTIONS = [...new Set(NEWS.filter((n) => !n.url).map((n) => require(path.join(ROOT, "story-url.js")).section(n.category)))];

function pages(dir) {
  let out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (["history", "news", "authors", "business-directory"].includes(path.relative(ROOT, p).split(path.sep)[0])) out = out.concat(pages(p)); }
    else if (e.name.endsWith(".html") && !SKIP.has(e.name) && !e.name.startsWith("google")) out.push(p);
  }
  return out;
}

// Google Tag Manager. It is added right after <head> on public pages, but gtm.js only
// loads once the visitor accepts analytics cookies (footer.js stores the choice and
// calls window.immaLoadGTM). Pages that can carry private data in their address
// (sign-in tokens, unsubscribe links, invoices, dashboards) do not get it.
const GTM_ID = "GTM-KZZ2PRJM";
const ADSENSE_CLIENT = "ca-pub-2355411100612093";   // Google AdSense publisher ID (also in ads.txt)
const NO_GTM = new Set(["signin.html", "account.html", "advertiser.html", "unsubscribe.html", "dashboard.html", "register.html"]);
const GTM_START = "<!-- GTM:START (generated by tools/build_footer.js) -->", GTM_END = "<!-- GTM:END -->";
const GTM = `${GTM_START}
  <script>
    window.dataLayer = window.dataLayer || [];
    function gtag(){dataLayer.push(arguments);}
    gtag('js', new Date());
    gtag('consent', 'default', { analytics_storage: 'denied', ad_storage: 'denied', ad_user_data: 'denied', ad_personalization: 'denied' });
    window.immaLoadGTM = function () {
      if (window.immaGTMLoaded) return; window.immaGTMLoaded = true;
      gtag('consent', 'update', { analytics_storage: 'granted' });
      dataLayer.push({ 'gtm.start': new Date().getTime(), event: 'gtm.js' });
      var s = document.createElement('script'); s.async = true;
      s.src = 'https://www.googletagmanager.com/gtm.js?id=${GTM_ID}';
      document.head.appendChild(s);
    };
    try { if ((JSON.parse(localStorage.getItem('imma_prefs_v1')) || {}).analytics === true) window.immaLoadGTM(); } catch (e) {}
  </script>
  ${GTM_END}`;

let changed = 0;
for (const file of pages(ROOT)) {
  let html = fs.readFileSync(file, "utf8");
  const before = html;
  const name = path.basename(file);
  let block = F.render(null, cats, year);
  if (NO_CTA.has(name)) block = block.replace(/<section class="sf-cta"[\s\S]*?<\/section>\n?/, "");
  block = `${START}\n${block}\n  ${END}`;

  if (html.includes(START)) {
    html = html.replace(new RegExp(START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "[\\s\\S]*?" + END), () => block);
  } else if (/<footer class="footer">[\s\S]*?<\/footer>/.test(html)) {
    html = html.replace(/<footer class="footer">[\s\S]*?<\/footer>/, () => block);
  } else {
    console.warn("No footer found in", path.relative(ROOT, file));
    continue;
  }
  // Google Tag Manager: remove any previous copy, then add it right after <head>
  const gs = html.indexOf(GTM_START);
  if (gs >= 0) {
    const ge = html.indexOf(GTM_END, gs);
    html = html.slice(0, gs) + html.slice(ge + GTM_END.length).replace(/^\s*/, "");
  }
  // Google AdSense site-ownership tag (loads nothing; just proves the site is ours)
  if (!html.includes("google-adsense-account")) html = html.replace(/(<meta charset="utf-8">)/i, `$1\n  <meta name="google-adsense-account" content="${ADSENSE_CLIENT}">`);
  // Right after <head> (keeping <meta charset> first so the browser reads the encoding early)
  if (!NO_GTM.has(name)) html = html.replace(/<head>\s*(<meta charset="utf-8">\s*)?/i, (m, cs) => "<head>\n  " + (cs ? cs.trim() + "\n  " : "") + GTM + "\n  ");
  if (!html.includes("footer.css")) html = html.replace(/(<link rel="stylesheet" href="[^"]*"[^>]*>)(?![\s\S]*<link rel="stylesheet")/, `$1\n  <link rel="stylesheet" href="/footer.css">`);
  // Font files come from fonts.gstatic.com: open that connection early (render-blocking otherwise)
  if (html.includes("fonts.googleapis.com/css2") && !html.includes('href="https://fonts.gstatic.com"'))
    html = html.replace(/(\s*)(<link rel="preconnect" href="https:\/\/fonts\.googleapis\.com">)/, '$1$2$1<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>');
  if (!/src="\/?config\.js"/.test(html)) html = html.replace("</body>", `  <script src="/config.js"></script>\n</body>`);
  if (!/<script src="\/?footer\.js">/.test(html)) html = html.replace("</body>", `  <script src="/footer.js"></script>\n</body>`);
  // ---------- Shared masthead (header.js) ----------
  const mast = `${HSTART}\n  <a class="skip-link" href="#main">Skip to main content</a>\n  ${H.render({ sections: SECTIONS })}\n  ${HEND}`;
  if (html.includes(HSTART)) {
    const a = html.indexOf(HSTART), b = html.indexOf(HEND, a) + HEND.length;
    html = html.slice(0, a) + mast + html.slice(b);
  } else {
    const m = /(?:\s*<a class="skip-link"[^>]*>[^<]*<\/a>)?\s*<header class="topbar">[\s\S]*?<\/header>/.exec(html);
    if (m) {
      // the directory keeps its own sub-navigation under the masthead
      const sub = /<nav class="catbar" aria-label="Business directory">([\s\S]*?)<\/nav>/.exec(m[0]);
      html = html.slice(0, m.index) + "\n  " + mast + (sub ? `\n  <nav class="catbar bd-subnav" aria-label="Business directory">${sub[1]}</nav>` : "") + html.slice(m.index + m[0].length);
    } else console.warn("No header found in", path.relative(ROOT, file));
  }
  if (!/<main[^>]*\bid=/.test(html)) html = html.replace(/<main(\s|>)/, '<main id="main"$1');
  if (!/<script src="\/?header\.js"/.test(html)) html = html.replace(/(\s*<script src="\/?footer\.js"><\/script>)/, '\n  <script src="/header.js" defer></script>$1');
  // ---------- Fonts: one request, three families (headline, reading, interface) ----------
  html = html.replace(/<link href="https:\/\/fonts\.googleapis\.com\/css2\?[^"]*" rel="stylesheet">/g, `<link href="${FONT_URL}" rel="stylesheet">`);
  // ---------- Dark mode chosen by the reader, applied before the page paints ----------
  if (!html.includes("imma_theme")) html = html.replace(/(<meta name="viewport"[^>]*>)/, `$1\n  <script>${H.THEME_BOOT}</script>`);
  if (html !== before) { fs.writeFileSync(file, html); changed++; console.log("updated", path.relative(ROOT, file)); }
}
console.log(`${changed} page(s) updated; categories with stories: ${[...cats].sort().join(", ")}`);

// ---------- RSS feed ----------
const SITE = "https://immanews.com";
const x = (s) => String(s == null ? "" : s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;" }[c]));
const U = require(path.join(ROOT, "story-url.js"));
const items = [
  ...NEWS.filter((s) => !s.url).map((s) => ({ ...s, link: SITE + U.storyPath(s) })),
  ...SERIES.map((s) => ({ ...s, link: SITE + s.url }))
].filter((s) => s.title && s.date).sort((a, b) => (a.date < b.date ? 1 : -1)).slice(0, 50);
const rfc = (d) => new Date(d + "T06:00:00+03:00").toUTCString();
const rss = `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
<channel>
  <title>IMMA News</title>
  <link>${SITE}/</link>
  <atom:link href="${SITE}/feed.xml" rel="self" type="application/rss+xml"/>
  <description>Kenya's news, insights and essential information from IMMA News, a publication of IMMA Media.</description>
  <language>en-ke</language>
  <copyright>© ${year} IMMA Media</copyright>
  <image><url>${SITE}/images/imma-news-emblem.png</url><title>IMMA News</title><link>${SITE}/</link></image>
  <lastBuildDate>${new Date().toUTCString()}</lastBuildDate>
${items.map((s) => `  <item>
    <title>${x(s.title)}</title>
    <link>${x(s.link)}</link>
    <guid isPermaLink="true">${x(s.link)}</guid>
    <pubDate>${rfc(s.date)}</pubDate>
    <category>${x(s.category)}</category>
    <description>${x(s.summary)}</description>
  </item>`).join("\n")}
</channel>
</rss>
`;
fs.writeFileSync(path.join(ROOT, "feed.xml"), rss);
console.log(`feed.xml: ${items.length} item(s)`);
