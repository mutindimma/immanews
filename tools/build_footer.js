// Bakes the global footer (footer.js DEFAULTS) into every public page as static HTML,
// and makes sure each page loads footer.css and footer.js. Also rebuilds feed.xml.
//
//   node tools/build_footer.js
//
// Run it after changing footer.js defaults, adding a page, or adding stories to news.js.
// Changes administrators make in the dashboard do not need a rebuild (they load live).
"use strict";
const fs = require("fs"), path = require("path"), vm = require("vm");
const ROOT = path.resolve(__dirname, "..");
const F = require(path.join(ROOT, "footer.js"));

const SKIP = new Set(["ads-admin.html", "resources-admin.html", "invoice.html", "google"]);   // admin / print pages
const START = "<!-- SITE-FOOTER:START (generated by tools/build_footer.js from footer.js; do not edit here) -->";
const END = "<!-- SITE-FOOTER:END -->";
const NO_CTA = new Set(["advertise.html", "advertiser.html"]);

// Story categories (for links shown only when a category has stories)
const sandbox = { window: {}, console };
vm.createContext(sandbox);
for (const f of ["news.js", "series-feed.js"]) {
  const p = path.join(ROOT, f);
  if (fs.existsSync(p)) vm.runInContext(fs.readFileSync(p, "utf8") + "\n;this.NEWS = typeof NEWS !== 'undefined' ? NEWS : this.NEWS;", sandbox);
}
const NEWS = sandbox.NEWS || [];
const SERIES = sandbox.window.SERIES_FEED || [];
const cats = new Set([...NEWS, ...SERIES].map((n) => n.category).filter(Boolean));
const year = new Date().getFullYear();

function pages(dir) {
  let out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (["history"].includes(path.relative(ROOT, p).split(path.sep)[0])) out = out.concat(pages(p)); }
    else if (e.name.endsWith(".html") && !SKIP.has(e.name) && !e.name.startsWith("google")) out.push(p);
  }
  return out;
}

let changed = 0;
for (const file of pages(ROOT)) {
  let html = fs.readFileSync(file, "utf8");
  const before = html;
  const name = path.basename(file);
  let block = F.render(null, cats, year);
  if (NO_CTA.has(name)) block = block.replace(/<section class="sf-cta"[\s\S]*?<\/section>\n?/, "");
  block = `${START}\n${block}\n  ${END}`;

  if (html.includes(START)) {
    html = html.replace(new RegExp(START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "[\\s\\S]*?" + END), () => block);
  } else if (/<footer class="footer">[\s\S]*?<\/footer>/.test(html)) {
    html = html.replace(/<footer class="footer">[\s\S]*?<\/footer>/, () => block);
  } else {
    console.warn("No footer found in", path.relative(ROOT, file));
    continue;
  }
  if (!html.includes("footer.css")) html = html.replace(/(<link rel="stylesheet" href="[^"]*"[^>]*>)(?![\s\S]*<link rel="stylesheet")/, `$1\n  <link rel="stylesheet" href="/footer.css">`);
  if (!/src="\/?config\.js"/.test(html)) html = html.replace("</body>", `  <script src="/config.js"></script>\n</body>`);
  if (!/<script src="\/?footer\.js">/.test(html)) html = html.replace("</body>", `  <script src="/footer.js"></script>\n</body>`);
  // Footer headings use the site's Playfair Display serif
  if (!html.includes("Playfair")) html = html.replace("family=Inter:wght@400;500;600;700;800&display=swap", "family=Inter:wght@400;500;600;700;800&family=Playfair+Display:wght@700&display=swap");
  if (html !== before) { fs.writeFileSync(file, html); changed++; console.log("updated", path.relative(ROOT, file)); }
}
console.log(`${changed} page(s) updated; categories with stories: ${[...cats].sort().join(", ")}`);

// ---------- RSS feed ----------
const SITE = "https://immanews.com";
const x = (s) => String(s == null ? "" : s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;" }[c]));
const storyKey = (s) => (s.date + "-" + s.title).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 120);   // same as auth.js
const items = [
  ...NEWS.map((s) => ({ ...s, link: `${SITE}/index.html?story=${storyKey(s)}` })),
  ...SERIES.map((s) => ({ ...s, link: SITE + s.url }))
].filter((s) => s.title && s.date).sort((a, b) => (a.date < b.date ? 1 : -1)).slice(0, 50);
const rfc = (d) => new Date(d + "T06:00:00+03:00").toUTCString();
const rss = `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
<channel>
  <title>IMMA News</title>
  <link>${SITE}/</link>
  <atom:link href="${SITE}/feed.xml" rel="self" type="application/rss+xml"/>
  <description>Kenya's news, insights and essential information from IMMA News, a publication of IMMA Media.</description>
  <language>en-ke</language>
  <copyright>© ${year} IMMA Media</copyright>
  <image><url>${SITE}/images/imma-news-emblem.png</url><title>IMMA News</title><link>${SITE}/</link></image>
  <lastBuildDate>${new Date().toUTCString()}</lastBuildDate>
${items.map((s) => `  <item>
    <title>${x(s.title)}</title>
    <link>${x(s.link)}</link>
    <guid isPermaLink="true">${x(s.link)}</guid>
    <pubDate>${rfc(s.date)}</pubDate>
    <category>${x(s.category)}</category>
    <description>${x(s.summary)}</description>
  </item>`).join("\n")}
</channel>
</rss>
`;
fs.writeFileSync(path.join(ROOT, "feed.xml"), rss);
console.log(`feed.xml: ${items.length} item(s)`);
